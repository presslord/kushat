function openRecipe(item) {
  const r = item.recipe;
  if (!r) return;
  document.getElementById("recipeTitle").textContent = `📖 ${item.name}`;
  const meta = [];
  if (item.kcal) meta.push(`🔥 ${item.kcal} ккал`);
  const bg = BASE_G[item.name] || getGramScale();
  if (bg > 0) meta.push(`⚖️ ~${bg} г`);
  if (r.timeMin) meta.push(`⏱ ${r.timeMin} мин`);
  let html = meta.length ? `<div class="recipe-meta">${meta.join(" · ")}</div>` : "";
  if (r.ingredients && r.ingredients.length) {
    html += `<div class="recipe-sub">🛒 Ингредиенты</div><ul class="recipe-list">` +
      r.ingredients.map(i => `<li>${i}</li>`).join("") + `</ul>`;
  }
  html += `<div class="recipe-sub">👩‍🍳 Приготовление</div><ol class="recipe-steps">` +
    r.steps.map(s => `<li>${s}</li>`).join("") + `</ol>`;
  document.getElementById("recipeBody").innerHTML = html;
  document.getElementById("recipeModal").style.display = "flex";
}
